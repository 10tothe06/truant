using UnityEngine;

public class ui_navigator : MonoBehaviour
{
    private static ui_navigator _instance;

    public static ui_navigator Instance
    {
        get => _instance;
        private set
        {
            if (_instance == null)
            {
                _instance = value;
            }
            else if (_instance != value)
            {
                Debug.Log("You messed up buddy.");
                Destroy(value);
            }
        }
    }

    void Awake()
    {
        Instance = this;
    }
}
